"""Writes Data/Forever/Geometry.lua without a trip into the game: the same as /mzr dumpgeometry on a Forever client.

    python tools/dump_geometry.py           # about 2 minutes; reads D:\\World of Warcraft (product wowf)

Run it after anything that changes walking: roads (gen_roads.py), steep ground (gen_steep.py), RoadNet.lua, or
nodes and containers.

How: the addon is loaded headless (tests/harness.py) and TravelGraph:BuildFreshGeometry prices every walk along the
roads, as the dump does in game. The one thing the client gives the dump is where each map lies in the world
(C_Map.GetWorldPosFromMapPos); here that comes from the client's own UiMapAssignment table, read from the local game
files, so the positions are the client's. Checked against an in-game dump (2026-11-18): every walk the same, bar a
few near-ties a fraction of a yard apart that tip a road choice by up to 2%.

The output is written the way MapzerothDataTools' writeGeometry writes it (Dev.lua): ids sorted, each pair once,
one decimal, and each map's median road / straight-line ratio (5 walks or more) as its mapFactor.
"""
import os
import struct
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(REPO, "tests"))
sys.path.insert(0, os.path.join(HERE, "roads"))
import harness                  # noqa: E402
import wdc5                     # noqa: E402
from casc import Casc           # noqa: E402

OUT = os.path.join(REPO, "Data", "Forever", "Geometry.lua")
UI_MAP_ASSIGNMENT = 1957219     # DBFilesClient/UiMapAssignment.db2


def map_bounds():
    """uiMapID -> (minX, minY, maxX, maxY, instance): the first assignment of each map, as the client places it."""
    out = {}
    for r in wdc5.read(Casc().read_fdid(UI_MAP_ASSIGNMENT)):
        if r["parent"] not in out:
            f = struct.unpack("<6f", r["vals"][2])
            out[r["parent"]] = (f[0], f[1], f[3], f[4], r["vals"][6])
    return out


LUA = r"""
local bounds = ...
C_Map = C_Map or {}
C_Map.GetWorldPosFromMapPos = function(mapID, v)
    local b = bounds[mapID]
    if not b then return nil end
    return b[5], CreateVector2D(b[3] - v.y * (b[3] - b[1]), b[4] - v.x * (b[4] - b[2]))
end
C_Map.GetMapInfo = C_Map.GetMapInfo or function() return nil end
C_TaxiMap = C_TaxiMap or { GetTaxiNodesForMap = function() return {} end }
addon.World:Build()
local nodeCount = 0
addon.World:ForEachNode(function() nodeCount = nodeCount + 1 end)
local ratios = {}
local geometry = addon.TravelGraph:BuildFreshGeometry({ roads = true, ratios = ratios })
-- Flattened for Python: { from, to, dtf, kind, ... } and { mapID, ratio, ... }.
local edges, r = {}, {}
for from, list in pairs(geometry) do
    for _, e in ipairs(list) do
        edges[#edges + 1] = from; edges[#edges + 1] = e[1]; edges[#edges + 1] = e[2]; edges[#edges + 1] = e[3]
    end
end
for mapID, list in pairs(ratios) do
    for _, v in ipairs(list) do r[#r + 1] = mapID; r[#r + 1] = v end
end
return nodeCount, edges, r
"""


def num(x):
    t = "%.1f" % x
    return t[:-2] if t.endswith(".0") else t


def median(values):
    values = sorted(values)
    n = len(values)
    return values[(n - 1) // 2] if n % 2 == 1 else (values[n // 2 - 1] + values[n // 2]) / 2


def write(node_count, edges, ratios):
    ids = sorted({e[0] for e in edges} | {e[1] for e in edges})
    index = {i: n + 1 for n, i in enumerate(ids)}
    by_low = {"walk": {}, "gate": {}, "fly": {}}
    seen = set()
    for a, b, dtf, kind in edges:
        i, j = index[a], index[b]
        lo, hi = min(i, j), max(i, j)
        if (kind, lo, hi) not in seen and kind in by_low:
            seen.add((kind, lo, hi))
            by_low[kind].setdefault(lo, []).append((hi, dtf))
    lines = [
        "-- Geometry.lua (Forever) -- GENERATED by /mzr dumpgeometry, do not hand-edit.",
        "-- Static travel geometry (walk/gate/fly edges), packed: see TravelGraph.lua's own comment for the",
        "-- format and why this is shipped instead of computed live. Regenerate before every version",
        "-- pushed to CurseForge that touches node or container data -- a stale dump is caught (the",
        "-- node count or an id below doesn't match) and ignored, not served wrong, but the caching",
        "-- benefit this file exists for is then lost until it's regenerated.",
        "",
        "local addonName, addon = ...",
        'if addon.RULESET ~= "forever" then return end   -- one addon for both games: this data is Forever\'s (Constants.lua)',
        "",
        "addon.GeometryPacked = {",
        "    nodeCount = %d," % node_count,
        "    ids = {",
    ]
    for i in range(0, len(ids), 4):
        lines.append("        " + ", ".join('"%s"' % x for x in ids[i:i + 4]) + ",")
    lines.append("    },")
    pairs = 0
    for kind in ("walk", "gate", "fly"):
        rows = []
        for i in range(1, len(ids) + 1):
            parts = ["%d,%s" % (hi, num(d)) for hi, d in sorted(by_low[kind].get(i, []), key=lambda p: p[0])]
            pairs += len(parts)
            if parts:
                rows.append("        { %d, %s }," % (i, ", ".join(parts)))
        if rows:
            lines += ["    %s = {" % kind] + rows + ["    },"]
    factors = {m: int(median(v) * 100 + 0.5) / 100 for m, v in ratios.items() if len(v) >= 5}
    if factors:
        maps = sorted(factors)
        lines.append("    mapFactors = {")
        for i in range(0, len(maps), 6):
            lines.append("        " + ", ".join("[%d] = %.2f" % (m, factors[m]) for m in maps[i:i + 6]) + ",")
        lines.append("    },")
    lines.append("}")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    return len(ids), pairs, len(factors)


def main():
    t0 = time.time()
    lua = harness.new_runtime()
    bounds = lua.table_from({m: lua.table_from(list(b)) for m, b in map_bounds().items()})
    node_count, flat, flat_ratios = lua.execute(LUA, bounds)
    flat, flat_ratios = list(flat.values()), list(flat_ratios.values())
    edges = [tuple(flat[k:k + 4]) for k in range(0, len(flat), 4)]
    ratios = {}
    for k in range(0, len(flat_ratios), 2):
        ratios.setdefault(int(flat_ratios[k]), []).append(flat_ratios[k + 1])
    nodes, pairs, maps = write(node_count, edges, ratios)
    print("wrote %s: %d nodes, %d node pairs, %d map factors (%.0fs)"
          % (os.path.relpath(OUT, REPO), nodes, pairs, maps, time.time() - t0))


if __name__ == "__main__":
    main()
