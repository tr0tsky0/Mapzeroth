"""Data/Forever/CityPaths.lua: each capital's streets, drawn by hand over its map art (tools/roads/city/<name>.json).

    python tools/roads/city/gen_city_paths.py

Lines are art pixels (1002 x 668 for the map's 0-1); they become map coordinates, keyed by the city's own map.
Points the editor joined are the same pixel, so they stay the same coordinate and join here too.
"""
import json
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from cities import CITIES, ART_W, ART_H, SKIP_CONTAINERS   # noqa: E402

REPO = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
OUT = os.path.join(REPO, "Data", "Forever", "CityPaths.lua")


def coord(v, size):
    return ("%.5f" % (v / size)).rstrip("0").rstrip(".")


def main():
    L = [
        "-- CityPaths.lua (Forever) -- GENERATED by tools/roads/city/gen_city_paths.py, do not hand-edit.",
        "-- Each capital's streets on its own map ({ x1, y1, x2, y2, ... }, map coordinates), drawn by hand over the",
        "-- map art in tools/roads/city. RoadNet.lua walks a city's walks along them, as it does the terrain's roads.",
        "",
        "local addonName, addon = ...",
        'if addon.RULESET ~= "forever" then return end   -- one addon for both games: this data is Forever\'s (Constants.lua)',
        "",
        "addon.CityPaths = {",
    ]
    for name, (ui_map, title) in sorted(CITIES.items(), key=lambda kv: kv[1][0]):
        path = os.path.join(HERE, name + ".json")
        if not os.path.exists(path):
            continue
        lines = json.load(open(path, encoding="utf-8"))
        L.append("    [%d] = {   -- %s" % (ui_map, title))
        for line in lines:
            L.append("        { " + ", ".join("%s,%s" % (coord(x, ART_W), coord(y, ART_H)) for x, y in line) + " },")
        L.append("    },")
        length = sum(math.dist(a, b) for l in lines for a, b in zip(l, l[1:]))
        print("%s (%d): %d lines, %d points, %.0f px of street" % (title, ui_map, len(lines), sum(len(l) for l in lines), length))
    L.append("}")
    L.append("")
    L.append("-- Containers on a city's map its streets aren't for (Undercity's ruins, above its streets): walks there stay straight.")
    L.append("addon.CityPathsSkip = {")
    for c in SKIP_CONTAINERS:
        L.append('    ["%s"] = true,' % c)
    L.append("}")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(L) + "\n")
    print("wrote", os.path.relpath(OUT, REPO))


if __name__ == "__main__":
    main()
