"""Generates Data/Modern/Stables.lua: Modern's stable masters, for the hunter's "Nearest Stable Master" pick
(Sections.lua), the same shape as Forever's stable nodes (Data/Forever/Pois.lua: kind "stable").

Source: tools/modern_source/stablemasters.tsv, scraped from retail Wowhead with tools/wowhead_scrape_retail.js on
https://www.wowhead.com/npcs?filter=27;1;0 (Wowhead's Stable Master flag: only 19 on retail) and from a list of NPC ids
(the script's MZR_IDS, from tools/stable_master_ids.py: a list page can't find NPCs by title). The same columns as innkeepers.tsv (tools/gen_modern_pois.py), one row per NPC per map:

    npcID  name  tag  zoneAreaID  uiMapID  floor  x,y (0-100: the middle of the biggest group of its spawns)  firstSeenPatch
    react ("a,h": 1 friendly to Alliance / Horde)

Steps (the inns' rules, tools/gen_modern_pois.py, reused where they apply):
  1. Keep rows of a stable master (STABLE_MASTER: "Stable Master" or "Stablemaster" in the name or title, not a stable
     hand or a stable's vendor), on a map the Modern node data has, and not in STABLE_DROP (tools/modern_inns.py). A row with only a
     zone and floor is placed by INN_FLOORS, the same floors the innkeepers stand on.
  2. Stable masters of one map standing a few steps apart are one stable. Its container is the one the map's unsplit
     nodes are in; on a phase-split map with no unsplit nodes, STABLE_PHASE says which side.
  3. A stable on a city's map belongs to that city (STABLE_CITIES by hand); anywhere else to the town (Pois.lua) whose
     inn is within TOWN_RADIUS, else to no town (it is named for its zone: "Durotar Stable Master").
  4. Faction: whoever its stable masters are friendly to, left off when that is both; when none has reactions on
     record (scraped by id), the faction of its town or city.

    python tools/gen_modern_stables.py
"""
import collections
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import gen_modern_pois as inns
import modern_inns as manual

ROOT = inns.ROOT
SOURCE = inns.SOURCE
OUT = inns.DATA / "Stables.lua"

CLUSTER_RADIUS = inns.CLUSTER_RADIUS    # stable masters this close are one stable
TOWN_RADIUS = 6.0                       # a stable this close to a town's inn is the town's
CITY_RADIUS = inns.CITY_RADIUS
STABLE_MASTER = re.compile(r"stable\s*master", re.I)

HEADER = [
    "-- Stables.lua (Modern) -- GENERATED by tools/gen_modern_stables.py, do not hand-edit.",
    "--",
    "-- Stable masters, for the hunter's Nearest Stable Master pick (Sections.lua). A stable is a city's or town's when",
    "-- it stands in one (named \"<place> Stable Master\"), else its zone's. `faction`: whose its stable masters serve,",
    "-- none for both (Relevance.lua).",
    "",
    "local addonName, addon = ...",
    'if addon.RULESET ~= "modern" then return end   -- one addon for both games: this data is Modern\'s (Constants.lua)',
    "",
    "addon.Nodes = addon.Nodes or {}",
]


def load_towns():
    """town key -> (mapID, its inn's spot 0-100), from the generated Pois.lua."""
    text = (inns.DATA / "Pois.lua").read_text(encoding="utf-8")
    body = text[text.index("addon.Towns"):text.index("addon.Nodes.Inns")]
    return {m.group(1): (int(m.group(2)), (float(m.group(3)) * 100, float(m.group(4)) * 100))
            for m in re.finditer(r"^\s*(\w+)\s*=\s*\{\s*mapID\s*=\s*(\d+),\s*x\s*=\s*([\d.]+),\s*y\s*=\s*([\d.]+)",
                                 body, re.M)}


def load_factions():
    """("city" | "town", key) -> its faction, from Settlements.lua's cities and Pois.lua's towns."""
    out = {}
    for kind, name, start, stop in (("city", "Settlements.lua", "addon.Cities", "addon.Towns"),
                                    ("town", "Pois.lua", "addon.Towns", "addon.Nodes.Inns")):
        text = (inns.DATA / name).read_text(encoding="utf-8")
        body = text[text.index(start):text.index(stop)]
        for m in re.finditer(r'^\s*(\w+)\s*=\s*\{[^\n]*faction\s*=\s*"(\w+)"', body, re.M):
            out[(kind, m.group(1))] = m.group(2)
    return out


def main():
    path = SOURCE / "stablemasters.tsv"
    if not path.exists():
        sys.exit(f"{path} is missing: scrape it with tools/wowhead_scrape_retail.js (see its header)")
    nodes = inns.load_nodes()
    containers = inns.map_containers(nodes)
    city_maps = inns.load_city_maps()
    area_maps = inns.load_area_maps()
    towns = load_towns()
    factions = load_factions()
    floors = getattr(manual, "INN_FLOORS", {})
    drop = set(getattr(manual, "STABLE_DROP", ()))
    phase = getattr(manual, "STABLE_PHASE", {})
    stable_cities = getattr(manual, "STABLE_CITIES", {})
    city_zone_maps = set(getattr(manual, "CITY_ZONE_MAPS", ()))

    report = collections.defaultdict(list)
    npcs, seen = [], set()
    with open(path, encoding="utf-8") as f:
        for line in f:
            if not line.strip() or line.startswith("#"):
                continue
            npc, name, tag, zone, ui_map, floor, spot, patch, react = (line.rstrip("\n").split("\t") + [""] * 9)[:9]
            npc = int(npc)
            if not (STABLE_MASTER.search(tag) or STABLE_MASTER.search(name)):
                report["not a stable master by name or title (left out)"].append(f"{npc} {name} <{tag}>")
                continue
            if npc in drop or (npc, int(ui_map or 0)) in drop:
                continue
            x, y = (float(v) for v in spot.split(","))
            if ui_map:
                map_id = int(ui_map)
            elif (int(zone or 0), floor) in floors:
                map_id = floors[(int(zone), floor)]
                if map_id is None:
                    continue
                if isinstance(map_id, str):     # a city's floor: the stable stands at the city's centre
                    map_id, (x, y) = next((m, c[1]) for m, cs in city_maps.items() for c in cs if c[0] == map_id)
            elif not floor and len(area_maps.get(int(zone or 0), ())) == 1:
                map_id = next(iter(area_maps[int(zone)]))
            else:
                report["only a zone and floor (add to INN_FLOORS)"].append(f"{npc} {name} zone {zone} floor {floor}")
                continue
            if map_id not in containers:
                report["on a map the Modern data doesn't have"].append(f"{npc} {name} map {map_id}")
                continue
            if (npc, map_id) in seen:
                continue
            seen.add((npc, map_id))
            a, _, h = react.partition(",")
            npcs.append({"id": npc, "name": name, "map": map_id, "pos": (x, y), "react": (a, h)})

    # Stable masters a few steps apart on one map are one stable (single linkage).
    stables = []
    by_map = collections.defaultdict(list)
    for n in npcs:
        by_map[n["map"]].append(n)
    for map_id, members in sorted(by_map.items()):
        remaining = sorted(members, key=lambda n: n["id"])
        while remaining:
            group = [remaining.pop(0)]
            grew = True
            while grew:
                grew = False
                for n in remaining[:]:
                    if any(inns.dist(n["pos"], g["pos"]) <= CLUSTER_RADIUS for g in group):
                        group.append(n)
                        remaining.remove(n)
                        grew = True
            group.sort(key=lambda g: g["id"])
            stables.append({"map": map_id, "members": group,
                            "pos": (sum(g["pos"][0] for g in group) / len(group),
                                    sum(g["pos"][1] for g in group) / len(group))})

    npc_maps = collections.Counter(s["members"][0]["id"] for s in stables)
    out = []
    for stable in stables:
        lead, map_id = stable["members"][0], stable["map"]
        options = containers[map_id]
        plain = [c for c in options if "_art" not in c]
        container = phase.get(lead["id"]) or (max(plain or options, key=lambda c: options[c])
                                              if plain or len(options) == 1 else None)
        if not container:
            report["only phase sides on its map (add to STABLE_PHASE)"].append(
                f"{lead['id']} {lead['name']} map {map_id}: {sorted(options)}")
            continue
        owner = None
        city = stable_cities.get(lead["id"])
        if not city and map_id in city_maps:
            key, centre = min(city_maps[map_id], key=lambda c: inns.dist(c[1], stable["pos"]))
            if map_id not in city_zone_maps or inns.dist(centre, stable["pos"]) <= CITY_RADIUS:
                city = key
        if city:
            owner = ("city", city)
        else:
            near = [(inns.dist(p, stable["pos"]), k) for k, (m, p) in towns.items() if m == map_id]
            near = [t for t in near if t[0] <= TOWN_RADIUS]
            if near:
                owner = ("town", min(near)[1])
            else:
                report["no town near: named for its zone (check)"].append(
                    f"{lead['id']} {lead['name']} map {map_id} at {stable['pos'][0]:.1f},{stable['pos'][1]:.1f}")
        reacts = [m["react"] for m in stable["members"] if any(m["react"])]
        faction = inns.faction_of(reacts) if reacts else (factions.get(owner, "Both") if owner else "Both")
        suffix = "" if npc_maps[lead["id"]] == 1 else f"_{map_id}"
        npc_list = ", ".join(f"{{ id = {m['id']} }}" for m in stable["members"])
        out.append(
            f'    {{ id = "STABLE_{lead["id"]}{suffix}", container = "{container}", mapID = {map_id}, '
            f'x = {stable["pos"][0] / 100:.4f}, y = {stable["pos"][1] / 100:.4f}, kind = "stable", '
            + (f'{owner[0]} = "{owner[1]}", ' if owner else "")
            + (f'faction = "{faction}", ' if faction != "Both" else "")
            + f'npcs = {{ {npc_list} }} }}, -- {lead["name"]}')

    OUT.write_text("\n".join(HEADER + ["addon.Nodes.Stables = {", *out, "}", ""]), encoding="utf-8")
    print(f"{len(npcs)} stable masters -> {len(stables)} stables, {len(out)} written")
    for reason, items in report.items():
        print(f"\n{len(items)} {reason}:")
        for item in items:
            print("  " + item)


if __name__ == "__main__":
    main()
